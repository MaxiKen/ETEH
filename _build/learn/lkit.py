def _lines(text, chars):
    return sum(max(1, math.ceil(len(p) / chars)) for p in str(text).split("\n"))


def _py(v):
    if v is None or v is pd.NaT:
        return None
    if isinstance(v, float) and np.isnan(v):
        return None
    if isinstance(v, np.integer):
        return int(v)
    if isinstance(v, np.floating):
        return None if np.isnan(v) else float(v)
    if isinstance(v, (pd.Timestamp, np.datetime64)):
        return pd.Timestamp(v).to_pydatetime()
    return v


def _q(s: str) -> str:
    return s.replace('"', '""')


class Ref:
    """Where a question's data lives: shown at the top of the sheet and in Start_Here."""

    def __init__(self, file, sheet=None, table=None, note=""):
        self.file, self.sheet, self.table, self.note = file, sheet, table, note

    def text(self):
        parts = [f"File: {self.file}"]
        if self.sheet:
            parts.append(f"Sheet: {self.sheet}")
        if self.table:
            parts.append(f"Table: {self.table}")
        s = "  ›  ".join(parts)
        return s + (f"   ({self.note})" if self.note else "")


class LBook:
    def __init__(self, path, filename, week_no, week_title, title_suffix="Section Examples", assignment=False,
                 with_solutions=True, intro=None, week_label=None):
        self.path, self.filename, self.week_no, self.week_title = path, filename, week_no, week_title
        self.week_label = week_label or f"Week {week_no}"
        self.assignment = assignment
        self.with_solutions = with_solutions
        self.intro = intro
        self.title_suffix = title_suffix
        self.wb = xlsxwriter.Workbook(str(path), {"use_future_functions": True, "nan_inf_to_errors": True,
                                                  "default_date_format": "yyyy-mm-dd", "strings_to_formulas": False,
                                                  "strings_to_numbers": False, "strings_to_urls": False})
        self.wb.set_properties({"title": f"ETEH {self.week_label} - {title_suffix}", "author": "ETEH Ltd - Eaglet2EagleHub Limited",
                                "company": "ETEH Ltd", "subject": week_title,
                                "comments": "Generated by _build/learn scripts; all data is training data."})
        f = self.wb.add_format
        base = {"font_name": "Calibri", "font_size": 10, "valign": "top"}
        self.base = base
        self.F = {
            "brand": f({**base, "italic": True, "font_color": "#555555"}),
            "title": f({**base, "bold": True, "font_size": 16, "font_color": NAVY}),
            "sub": f({**base, "bold": True, "font_size": 11, "font_color": TEAL}),
            "h2": f({**base, "bold": True, "font_size": 11, "font_color": "white", "bg_color": NAVY, "valign": "vcenter"}),
            "part": f({**base, "bold": True, "font_size": 11, "font_color": TEAL, "bottom": 1, "bottom_color": TEAL}),
            "lab": f({**base, "bold": True, "text_wrap": True, "bg_color": PALE, "border": 1, "border_color": "#C9D6E2"}),
            "info": f({**base, "text_wrap": True, "bg_color": PALE, "border": 1, "border_color": "#C9D6E2"}),
            "data": f({**base, "text_wrap": True, "bold": True, "font_color": "#0B5394", "bg_color": "#FFF8E1",
                       "border": 1, "border_color": GOLD}),
            "hdr": f({**base, "bold": True, "font_color": "white", "bg_color": TEAL, "border": 1, "text_wrap": True,
                      "valign": "vcenter"}),
            "qno": f({**base, "bold": True, "font_color": NAVY, "bg_color": GOLD, "align": "center", "border": 1}),
            "q": f({**base, "text_wrap": True, "border": 1, "border_color": "#BBBBBB"}),
            "type": f({**base, "text_wrap": True, "italic": True, "font_color": "#555555", "border": 1, "border_color": "#BBBBBB"}),
            "in": f({**base, "bg_color": "#FFFFFF", "border": 2, "border_color": GOLD, "text_wrap": True}),
            "chk": f({**base, "bold": True, "font_color": "#1B5E20", "text_wrap": True, "border": 1, "border_color": "#BBBBBB"}),
            "cell": f({**base, "text_wrap": True, "border": 1, "border_color": "#BBBBBB"}),
            "code": f({"font_name": "Consolas", "font_size": 9, "text_wrap": True, "valign": "top", "bg_color": GREY,
                       "border": 1, "border_color": "#BBBBBB", "font_color": "#0B5394"}),
            "link": f({**base, "font_color": "blue", "underline": 1}),
            "linkb": f({**base, "font_color": "blue", "underline": 1, "border": 1, "border_color": "#BBBBBB"}),
            "note": f({**base, "italic": True, "text_wrap": True, "font_color": "#555555"}),
            "marks": f({**base, "align": "center", "border": 1, "border_color": "#BBBBBB"}),
        }
        self._nf = {}
        self.modules: list[LSheet] = []
        self.datas: list[dict] = []
        self.sol_rows: list[dict] = []           # filled by LSheet questions
        self.tables: dict[str, str] = {}          # table -> sheet
        self.copy_jobs: list = []                 # (folder name, [source paths])
        self.start = self.wb.add_worksheet("Start_Here")
        self._sol_ws = None

    def nf(self, kind, **extra):
        key = (kind, tuple(sorted(extra.items())))
        if key not in self._nf:
            p = {**self.base, "num_format": NUM.get(kind, kind)}
            p.update(extra)
            self._nf[key] = self.wb.add_format(p)
        return self._nf[key]

    # ------------------------------------------------------------------ sheets
    def module(self, code, sheet, title, learned, refs=(), files_folder=None):
        s = LSheet(self, code, sheet, title, learned, refs, files_folder)
        self.modules.append(s)
        return s

    def data(self, name, df, desc, fmts=None, widths=None, used_in="", calc=None):
        """Sheet Data_<name> holding table t<name> in A1."""
        sheet, table = f"Data_{name}", f"t{name}"
        assert len(sheet) <= 31 and table not in self.tables
        ws = self.wb.add_worksheet(sheet)
        fmts = fmts or {}
        cols = []
        for c in df.columns:
            kind = fmts.get(c)
            if kind is None:
                if pd.api.types.is_datetime64_any_dtype(df[c]):
                    kind = "date"
                elif pd.api.types.is_float_dtype(df[c]):
                    kind = "dec2"
                elif pd.api.types.is_integer_dtype(df[c]):
                    kind = "int" if df[c].abs().max() > 9999 else "gen"
            spec = {"header": str(c)}
            if kind:
                spec["format"] = self.nf(kind)
            cols.append(spec)
        calc = calc or {}
        for c, (fx, kind, _cached) in calc.items():
            cols.append({"header": c, "formula": fx, "format": self.nf(kind)})
        rows = [[_py(v) for v in rec] for rec in df.itertuples(index=False)]
        ws.add_table(0, 0, max(len(df), 1), len(cols) - 1,
                     {"name": table, "style": "Table Style Medium 2", "columns": cols, "data": rows})
        from xlsxwriter.worksheet import Worksheet as _W
        for k, (c, (fx, kind, cached)) in enumerate(calc.items()):
            j = len(df.columns) + k
            for i, v in enumerate(cached):
                ws.write_formula(1 + i, j, "=" + _W._prepare_table_formula(fx.lstrip("=")), self.nf(kind), _py(v))
            ws.set_column(j, j, max(len(c) + 3, 11))
        for j, c in enumerate(df.columns):
            w = (widths or {}).get(c) or min(max(len(str(c)) + 3, int(df[c].astype(str).str.len().quantile(0.9)) + 2), 40)
            ws.set_column(j, j, w)
        ws.freeze_panes(1, 0)
        self.tables[table] = sheet
        self.datas.append(dict(sheet=sheet, table=table, rows=len(df), desc=desc, used_in=used_in,
                               cols=", ".join(map(str, df.columns))))
        return Ref(self.filename, sheet, table)

    def ref(self, table, note=""):
        return Ref(self.filename, self.tables[table], table, note)

    # ------------------------------------------------------------------ build
    def close(self):
        for m in self.modules:
            m.finish()
        if self.with_solutions:
            self._solutions()
        self._start()
        self.start.activate()
        self.wb.close()
        self._sidecar()
        self._copy()

    def _copy(self):
        import shutil
        base = Path(self.path).parent
        for folder, files in self.copy_jobs:
            dest = base / folder
            dest.mkdir(parents=True, exist_ok=True)
            for f in files:
                if f.is_dir():
                    shutil.copytree(f, dest / f.name, dirs_exist_ok=True)
                else:
                    shutil.copy2(f, dest / f.name)

    def _sidecar(self):
        """Answer map for the self-test (_build/learn/selftest.py); kept in the git-ignored stage folder."""
        import json
        from common import STAGE
        STAGE.mkdir(parents=True, exist_ok=True)
        out = [dict(sheet=r["sheet"], cell=r["cell"], kind=r["kind"], answer=(r["value"] if r["kind"] == "num" else
                    (r["answer"].split(".")[0] if r["kind"] == "mc" else r["answer"])), fmt=r["fmt"],
                    dynamic=bool(r.get("dynamic") and r.get("formula"))) for r in self.sol_rows]
        (STAGE / (Path(self.path).stem + ".answers.json")).write_text(json.dumps(out, default=str, indent=0))

    def _solutions(self):
        ws = self.wb.add_worksheet("Solutions")
        self._sol_ws = ws
        ws.hide_gridlines(2)
        F = self.F
        ws.set_column("A:A", 2)
        ws.set_column("B:B", 10)
        ws.set_column("C:C", 6)
        ws.set_column("D:D", 58)
        ws.set_column("E:E", 26)
        ws.set_column("F:F", 62)
        ws.write_url("B1", "internal:'Start_Here'!A1", F["link"], "◄ Start_Here")
        ws.write("B2", f"{self.week_label} · Solutions" + (" (answer key)" if self.assignment else ""), F["title"])
        ws.merge_range("B3:F3", "Try each question first, then come here to check your reasoning. Number answers are live "
                       "formulas on the workbook's own tables, so you can click them and see exactly how they were worked out.",
                       F["note"])
        ws.set_row(2, 28)
        hdr = ["Sheet", "Q", "Question", "Answer", "How to get it"]
        r = 4
        last_sheet = None
        for row in self.sol_rows:
            if row["sheet"] != last_sheet:
                r += 1 if last_sheet else 0
                ws.merge_range(r, 1, r, 5, f"{row['code']}  {row['title']}", F["h2"])
                ws.set_row(r, 18)
                r += 1
                for j, h in enumerate(hdr):
                    ws.write(r, 1 + j, h, F["hdr"])
                r += 1
                last_sheet = row["sheet"]
            ws.write_url(r, 1, f"internal:'{row['sheet']}'!{row['cell']}", F["linkb"], row["code"])
            ws.write(r, 2, row["qid"], F["qno"])
            ws.write(r, 3, row["qtext"], F["cell"])
            if row["formula"]:
                fx = row["formula"]
                fmt = self.nf(row["fmt"], bold=True, border=1, border_color="#2E7D32", bg_color=GREEN)
                if row.get("dynamic"):
                    ws.write_dynamic_array_formula(r, 4, r, 4, fx, fmt, row["value"])
                else:
                    ws.write_formula(r, 4, fx, fmt, row["value"])
            else:
                ws.write(r, 4, row["answer"], self.nf("gen", bold=True, border=1, border_color="#2E7D32",
                                                      bg_color=GREEN, text_wrap=True))
            ws.write(r, 5, row["how"], F["cell"])
            row["sol_cell"] = xl_rowcol_to_cell(r, 4, row_abs=True, col_abs=True)
            h = max(_lines(row["qtext"], 62), _lines(row["how"], 66), _lines(str(row["answer"]), 28))
            ws.set_row(r, 13.5 * h + 3)
            r += 1
        ws.freeze_panes(5, 0)
        # now that solution cells are known, write numeric checks
        for row in self.sol_rows:
            if row["kind"] == "num":
                row["sheet_obj"].write_num_check(row)

    def _start(self):
        ws = self.start
        F = self.F
        ws.hide_gridlines(2)
        ws.set_column("A:A", 2)
        ws.set_column("B:B", 26)
        ws.set_column("C:C", 44)
        ws.set_column("D:D", 40)
        ws.set_column("E:E", 12)
        ws.set_column("F:F", 52)
        ws.write("B1", BRAND, F["brand"])
        ws.write("B2", f"{self.week_label} · {self.title_suffix}", F["title"])
        ws.write("B3", self.week_title, F["sub"])
        r = 4
        how = self.intro or default_intro(self)
        ws.merge_range(r, 1, r, 5, "How to use this workbook", F["h2"]); r += 1
        for i, line in enumerate(how, 1):
            ws.write(r, 1, f"Step {i}", F["lab"])
            ws.merge_range(r, 2, r, 5, line, F["info"])
            ws.set_row(r, 13.5 * _lines(line, 140) + 3)
            r += 1
        r += 1
        ws.merge_range(r, 1, r, 5, "Sheets in teaching order (click a name to open it)", F["h2"]); r += 1
        for j, h in enumerate(["Sheet", "Module", "Data this sheet uses (File › Sheet › Table)", "Questions",
                               "Question types"]):
            ws.write(r, 1 + j, h, F["hdr"])
        r += 1
        for m in self.modules:
            ws.write_url(r, 1, f"internal:'{m.name}'!A1", F["linkb"], m.name)
            ws.write(r, 2, f"{m.code}  {m.title}", F["cell"])
            data = "\n".join(x.text() for x in m.refs) if m.refs else ("" if m.files_folder else "No data: answer from the slides")
            if m.files_folder:
                data = (data + "\n" if data else "") + "Files: " + m.files_folder.split(",")[0].replace("Folder ", "")
            ws.write(r, 3, data, F["cell"])
            ws.write(r, 4, m.nq, F["marks"])
            ws.write(r, 5, ", ".join(TYPE_LABEL[k] for k in m.kinds_order()), F["cell"])
            ws.set_row(r, 13.5 * max(_lines(data, 46), _lines(m.title, 40)) + 3)
            r += 1
        if self.datas:
            r += 1
            ws.merge_range(r, 1, r, 5, "Data sheets in this workbook", F["h2"]); r += 1
            ws.merge_range(r, 1, r, 5, "Naming standard used in every ETEH workbook: sheet Data_<Name> holds exactly one "
                           "Excel table called t<Name>, starting in cell A1 (one header row, then one row per record). "
                           "A two-digit suffix is the year the table covers, e.g. tStores25 = financial year 2025. "
                           "Use the data sheets as read-only raw data; practise on a copy (right-click the tab › Move or Copy).",
                           F["info"])
            ws.set_row(r, 42); r += 1
            for j, h in enumerate(["Sheet", "Table", "What one row is", "Rows", "Used in"]):
                ws.write(r, 1 + j, h, F["hdr"])
            r += 1
            for d in self.datas:
                ws.write_url(r, 1, f"internal:'{d['sheet']}'!A1", F["linkb"], d["sheet"])
                ws.write(r, 2, d["table"], F["cell"])
                ws.write(r, 3, d["desc"], F["cell"])
                ws.write(r, 4, d["rows"], self.nf("int", border=1, border_color="#BBBBBB", align="center"))
                ws.write(r, 5, d["used_in"], F["cell"])
                ws.set_row(r, 13.5 * _lines(d["desc"], 40) + 3)
                r += 1
        if self.with_solutions:
            r += 1
            ws.write_url(r, 1, "internal:'Solutions'!A1", F["linkb"], "Solutions")
            ws.merge_range(r, 2, r, 5, "Every answer in this workbook, with a one-line explanation. Try the question first.",
                           F["cell"])
        ws.set_landscape()
        ws.fit_to_pages(1, 0)


def default_intro(b):
    lines = [f"Work through the sheets in order. Open sheet {b.modules[0].code if b.modules else ''} after the matching "
             "module in the slides, and so on: each sheet only asks about what has been taught up to that module.",
             "The gold box at the top of every sheet tells you exactly which data to use: the File, the Sheet and the "
             "Table. 'No data' means the questions are answered from the slides.",
             "Answer in the white cell with the gold border (column E). Multiple choice, Yes/No and True/False have a "
             "drop-down list. Short answers are one word or phrase. Number answers: type the number only (no ₦ sign "
             "needed); percentages can be typed as 25% or 0.25.",
             "Column F tells you straight away: ✓ Correct or ✗ Try again.",
             ]
    if b.with_solutions:
        lines.append("Stuck? The Solutions sheet (last tab) has every answer and a short explanation of how to get it.")
    return lines


class LSheet:
    COLS = {"A": 2, "B": 7, "C": 74, "D": 15, "E": 22, "F": 16}

    def __init__(self, book: LBook, code, name, title, learned, refs, files_folder):
        assert len(name) <= 31, name
        self.b, self.code, self.name, self.title = book, code, name, title
        self.refs = list(refs)
        self.files_folder = files_folder
        self.ws = book.wb.add_worksheet(name)
        self.n = 0
        self.kinds = []
        ws, F = self.ws, book.F
        ws.hide_gridlines(2)
        for c, w in self.COLS.items():
            ws.set_column(f"{c}:{c}", w)
        ws.write_url("B1", "internal:'Start_Here'!A1", F["link"], "◄ Start_Here")
        if book.with_solutions:
            ws.write_url("E1", "internal:'Solutions'!A1", F["link"], "Solutions ►")
        ws.write("B2", f"Module {code}  ·  {title}", F["title"])
        self.learned = learned
        self.r = 6          # rows 3-5 are written in finish(): You learned / Data to use / Files folder

    def link_files(self, files, folder=None):
        """Copy external files next to the workbook in Ex<code>_Files and list them in the gold box.
        files: list of source paths (a folder is copied whole). Returns the folder name."""
        folder = folder or f"Ex{self.code}_Files"
        self.b.copy_jobs.append((folder, [Path(f) for f in files]))
        names = ", ".join(Path(f).name + (" (a folder of files)" if Path(f).is_dir() else "") for f in files)
        self.files_folder = (f"Folder {folder}, next to this workbook in the {Path(self.b.path).parent.name} folder. "
                             f"It holds: {names}")
        return folder

    def set_refs(self, refs, files_folder=None):
        self.refs = list(refs)
        if files_folder:
            self.files_folder = files_folder

    def _header(self):
        keep = self.r
        self.r = 2
        self.info("You learned", self.learned)
        if self.refs:
            self.info("Data to use", "\n".join(x.text() for x in self.refs), fmt="data")
        else:
            self.info("Data to use", "No data needed: answer from what you learned in the slides.", fmt="data")
        if self.files_folder:
            self.info("Files folder", self.files_folder, fmt="data")
        self.r = keep

    # ------------------------------------------------------------------ layout helpers
    def info(self, label, text, fmt="info"):
        ws, F = self.ws, self.b.F
        ws.write(self.r, 1, label, F["lab"])
        ws.merge_range(self.r, 2, self.r, 5, text, F[fmt])
        ws.set_row(self.r, 13.5 * _lines(text, 120) + 4)
        self.r += 1

    def part(self, title):
        self.ws.merge_range(self.r, 1, self.r, 5, title, self.b.F["h2"])
        self.ws.set_row(self.r, 18)
        self.r += 1
        self._qhdr = False

    def note(self, text):
        self.ws.merge_range(self.r, 1, self.r, 5, text, self.b.F["note"])
        self.ws.set_row(self.r, 13.5 * _lines(text, 125) + 3)
        self.r += 1

    def example(self, title, steps, rows=()):
        """A short worked example: numbered steps, then (label, formula text, live formula, cached value, fmt) rows."""
        F, ws = self.b.F, self.ws
        self.part("Worked example: " + title)
        for i, s in enumerate(steps, 1):
            ws.write(self.r, 1, i, F["qno"])
            ws.merge_range(self.r, 2, self.r, 5, s, F["cell"])
            ws.set_row(self.r, 13.5 * _lines(s, 120) + 3)
            self.r += 1
        if rows:
            for j, h in enumerate(["", "What we work out", "Formula typed", "", "Result"]):
                if j == 2:
                    ws.merge_range(self.r, 3, self.r, 4, h, F["hdr"])
                elif j != 3:
                    ws.write(self.r, 1 + j, h, F["hdr"])
            self.r += 1
            for lab, ftext, fx, val, fmt in rows:
                ws.write(self.r, 1, "", F["cell"])
                ws.write(self.r, 2, lab, F["cell"])
                ws.merge_range(self.r, 3, self.r, 4, ftext, F["code"])
                rf = self.b.nf(fmt, bold=True, border=1, border_color="#2E7D32", bg_color=GREEN)
                if fx is None:
                    ws.write(self.r, 5, val, rf)
                else:
                    ws.write_formula(self.r, 5, fx, rf, val)
                ws.set_row(self.r, 13.5 * max(_lines(lab, 70), _lines(ftext, 34)) + 3)
                self.r += 1
        self.r += 1

    def _qheader(self):
        F, ws = self.b.F, self.ws
        last = "Check" if self.b.with_solutions else "Marks"
        for j, h in enumerate(["Q", "Question", "Type", "Your answer", last]):
            ws.write(self.r, 1 + j, h, F["hdr"])
        self.r += 1
        self._qhdr = True

    def _row(self, kind, text, options=None):
        if not getattr(self, "_qhdr", False):
            self._qheader()
        self.n += 1
        self.kinds.append(kind)
        F, ws, r = self.b.F, self.ws, self.r
        full = text
        if options:
            full = text + "\n" + "\n".join(f"{'ABCD'[i]}.  {o}" for i, o in enumerate(options))
        ws.write(r, 1, f"Q{self.n}", F["qno"])
        ws.write(r, 2, full, F["q"])
        ws.write(r, 3, DIRECT[kind], F["type"])
        mk = 2 if kind in ("num", "do") else 1
        self.marks = getattr(self, "marks", 0) + mk
        if not self.b.with_solutions:
            ws.write(r, 5, mk, F["marks"])
        ws.set_row(r, 13.5 * _lines(full, 82) + 4)
        self.r += 1
        return r, full

    def _sol(self, kind, r, qtext, answer, how, formula=None, value=None, fmt="gen", tol=None, dynamic=False):
        self.b.sol_rows.append(dict(sheet=self.name, code=self.code, title=self.title, qid=f"Q{self.n}", qtext=qtext,
                                    answer=answer, how=how, formula=formula, value=value, fmt=fmt, kind=kind, row=r,
                                    cell=xl_rowcol_to_cell(r, 4), tol=tol, sheet_obj=self, dynamic=dynamic))

    def _lit_check(self, r, accepted):
        if not self.b.with_solutions:
            return
        inp = xl_rowcol_to_cell(r, 4)
        conds = ",".join(f'LOWER(TRIM({inp}))="{_q(str(a).lower())}"' for a in accepted)
        self.ws.write_formula(r, 5, f'=IF({inp}="","",IF(OR({conds}),"✓ Correct","✗ Try again"))', self.b.F["chk"], "")

    # ------------------------------------------------------------------ question types
    def mc(self, text, options, answer, how):
        assert answer in "ABCD"[:len(options)] and len(answer) == 1
        r, full = self._row("mc", text, options)
        self.ws.write_blank(r, 4, None, self.b.F["in"])
        self.ws.data_validation(r, 4, r, 4, {"validate": "list", "source": list("ABCD"[:len(options)])})
        self._lit_check(r, [answer])
        self._sol("mc", r, text, f"{answer}.  {options['ABCD'.index(answer)]}", how)

    def yn(self, text, answer, how):
        assert answer in ("Yes", "No")
        r, _ = self._row("yn", text)
        self.ws.write_blank(r, 4, None, self.b.F["in"])
        self.ws.data_validation(r, 4, r, 4, {"validate": "list", "source": ["Yes", "No"]})
        self._lit_check(r, [answer])
        self._sol("yn", r, text, answer, how)

    def tf(self, text, answer: bool, how):
        a = "True" if answer else "False"
        r, _ = self._row("tf", text)
        self.ws.write_blank(r, 4, None, self.b.F["in"])
        self.ws.data_validation(r, 4, r, 4, {"validate": "list", "source": ["True", "False"]})
        # Excel turns a typed True into the logical TRUE; LOWER(TRIM(TRUE)) = "true" so the check still works.
        self._lit_check(r, [a])
        self._sol("tf", r, text, a, how)

    def pick(self, text, choices, answer, how):
        """Choose one word from a short drop-down list, e.g. Data / Information."""
        assert answer in choices
        r, _ = self._row("pick", text)
        self.ws.write_blank(r, 4, None, self.b.F["in"])
        self.ws.data_validation(r, 4, r, 4, {"validate": "list", "source": list(choices)})
        self._lit_check(r, [answer])
        self._sol("pick", r, text, answer, how)

    def short(self, text, answer, how, alts=(), kind="short"):
        r, _ = self._row(kind, text)
        self.ws.write_blank(r, 4, None, self.b.F["in"])
        self._lit_check(r, [answer, *alts])
        self._sol(kind, r, text, answer, how)

    def do(self, text, answer, how, alts=()):
        """A hands-on task whose result is a word / short text (e.g. 'which store is now at the top?')."""
        self.short(text, answer, how, alts, kind="do")

    def num(self, text, formula, value, how, fmt="int", tol=None, do=False, dynamic=False):
        """Number answer. `formula` is the live Excel formula placed on the Solutions sheet (or None for a typed value)."""
        kind = "do" if do else "num"
        r, _ = self._row(kind, text)
        self.ws.write_blank(r, 4, None, self.b.nf(fmt, bg_color="#FFFFFF", border=2, border_color=GOLD))
        if tol is None:
            tol = {"pct": 0.0006, "pct0": 0.006, "pct2": 0.00006, "dec1": 0.051, "dec2": 0.0051, "dec3": 0.00051}.get(fmt, 0.5)
        self.kinds[-1] = kind
        self._sol("num", r, text, value, how, formula=formula, value=value, fmt=fmt, tol=tol, dynamic=dynamic)

    def write_num_check(self, row):
        r, inp = row["row"], xl_rowcol_to_cell(row["row"], 4)
        key = f"Solutions!{row['sol_cell']}"
        tol = row["tol"]
        if row["fmt"].startswith("pct"):
            ok = f"OR(ABS({inp}-{key})<={tol},ABS({inp}/100-{key})<={tol})"
        else:
            ok = f"ABS({inp}-{key})<={tol}"
        fx = f'=IF({inp}="","",IF(ISNUMBER({inp}),IF({ok},"✓ Correct","✗ Try again"),"✗ Type a number only"))'
        self.ws.write_formula(r, 5, fx, self.b.F["chk"], "")

    # ------------------------------------------------------------------ finish
    @property
    def nq(self):
        return self.n

    def kinds_order(self):
        seen = []
        for k in self.kinds:
            if k not in seen:
                seen.append(k)
        return seen

    def finish(self):
        self._header()
        self.ws.freeze_panes(2, 0)
        self.ws.set_landscape()
        self.ws.fit_to_pages(1, 0)
        self.ws.repeat_rows(0, 1)
