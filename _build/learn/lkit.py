"""Learner workbook kit (Edition 3.1): one simple, consistent layout for every weekly workbook.

Every workbook built with this kit has the same tabs, in this order:

    Start_Here     how to use the workbook, the naming standard, and a map of every sheet (with links)
    <module>       one sheet per slide module, in teaching order, e.g. "1.1 Intro to Analytics"
                   top:    what you learned in the module, and the exact data the sheet uses
                           (File › Sheet › Table, or the folder that holds a linked file)
                   middle: an optional short worked example
                   bottom: questions (multiple choice, yes/no, true/false, short answer, number)
    Data_<Name>    one Excel table per sheet, starting in A1; the table is called t<Name>
    Solutions      every answer, with a one-line "how to get it"

Questions only use what the slides have taught up to and including that module; the content files
(learn/w1.py ...) are written in teaching order and say which module they belong to.

Answer checking
    The learner types (or picks from a drop-down) in column E; column F shows "✓ Correct" or "✗ Try again".
    Number answers are compared with the live formula on the Solutions sheet; letters / words are
    compared with the accepted answers written into the check formula.
"""
