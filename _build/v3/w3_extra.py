GLOSSARY = sorted([
    ("Aggregate function", "A function that summarises many rows into one value: COUNT, SUM, AVG, MIN, MAX."),
    ("Anti join", "A join that returns the rows of one table with no match in the other."),
    ("Conditional Column", "A Power Query column built with if-then-else rules from a form, such as a Net / Not net flag."),
    ("Custom Column", "A Power Query column calculated on every row from other columns, such as [quantity] * [unit_price]."),
    ("Cardinality", "How many rows match on each side of a relationship: one-to-one, one-to-many."),
    ("Connection string", "Text holding the driver, database location and options for a data connection."),
    ("Dashboard", "One screen that monitors a few agreed KPIs for one audience, using live data."),
    ("Data Model", "The in-workbook database (Power Pivot engine) that holds related tables for PivotTables."),
    ("Date table", "A dimension with one row per calendar day and no gaps, marked as the model's date table."),
    ("Distinct Count", "A PivotTable summary (Data Model only) that counts different values, such as unique customers."),
    ("Dimension table", "A table describing the who, what, where and when used to filter and group facts."),
    ("DSN", "Data Source Name: a named ODBC connection saved on one computer."),
    ("Fact table", "A table of measurable events at a stated grain, with keys to dimension tables."),
    ("Group By", "The Power Query step that returns one row per group with sums or counts."),
    ("Foreign key", "A column whose values must match the primary key of another table."),
    ("Grain", "What one row of a table represents, such as one order line or one admission."),
    ("GROUP BY", "The SQL clause that returns one row per group, with COUNT, SUM or AVG for each group."),
    ("Index", "A sorted lookup structure that lets the database find rows without reading the whole table."),
    ("M", "The language Power Query writes for every step; seen in the formula bar, used here for cleaning."),
    ("Join", "Combining two tables side by side by matching key values."),
    ("KPI", "Key performance indicator: a defined number compared with a target."),
    ("Merge Queries", "The Power Query command that joins two queries on a key column, with a chosen join kind."),
    ("Relational database", "Data stored in linked tables, each fact once, joined by keys."),
    ("ODBC", "Open Database Connectivity: a standard interface between applications and databases."),
    ("OLAP / OLTP", "Analytical processing over history / transaction processing of many small writes."),
    ("Primary key", "A column whose value is unique and not empty, identifying one row."),
    ("Running Total In", "A Show Values As option that adds each period to the ones before it: year to date."),
    ("Show Values As", "A PivotTable setting that re-expresses a value as a share, difference or running total."),
    ("Slicer", "A panel of filter buttons that can drive several PivotTables at once."),
    ("SQL", "Structured Query Language: the standard language for relational databases."),
    ("Star schema", "A model with one fact table joined directly to its dimension tables."),
    ("Append Queries", "The Power Query command that stacks tables with the same column names."),
    ("View", "A stored query that can be queried like a table."),
], key=lambda kv: kv[0].lower())
