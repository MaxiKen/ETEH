GLOSSARY = sorted([
    ("Advanced Editor", "The Power Query window that shows a whole query as one M script."),
    ("Applied Steps", "The ordered list of recorded transformations in a query (Query Settings pane)."),
    ("Calculated field", "A pivot value field computed from the sums of other fields, e.g. Profit / Sales."),
    ("Column quality", "Power Query profile showing the % of valid, error and empty values in a column."),
    ("Combine Files", "Power Query command that applies one transformation to every file in a folder and appends them."),
    ("Connection only", "A query that is saved but not loaded to a sheet; used for staging."),
    ("Control total", "An agreed figure from the source (rows, total sales) that cleaned data must match."),
    ("Delimiter", "The character that separates fields in a text file: comma, semicolon, pipe or tab."),
    ("Dynamic array", "A formula result that spills into several cells, e.g. FILTER, UNIQUE, SORT."),
    ("Encoding", "The code table that turns bytes into characters, e.g. UTF-8 or Windows-1252."),
    ("ETL", "Extract, Transform, Load: read data, clean and reshape it, then write it where it is analysed."),
    ("Group By", "Collapsing rows that share values into one row each, with aggregations."),
    ("Locale", "Regional rules for numbers and dates: decimal mark, separators, day/month order."),
    ("M language", "The case-sensitive formula language in which Power Query steps are written."),
    ("Merge Queries", "Power Query join of two tables on matching key columns."),
    ("Navigator", "The window that lists the sheets, tables or pages found in a source."),
    ("null", "Power Query's empty value: no value at all, not zero and not empty text."),
    ("Parameter", "A named value, such as a folder path, used by queries instead of a typed constant."),
    ("Pivot cache", "The copy of the source data a PivotTable summarises; updated only on refresh."),
    ("PivotChart", "A chart drawn from a PivotTable and kept in sync with it."),
    ("PivotTable", "An interactive summary that groups a table's rows and aggregates its values."),
    ("Power Query", "Excel's data connection and preparation engine (Get & Transform)."),
    ("Reconciliation", "Checking figures against the system of record and explaining every difference."),
    ("Reference (query)", "A query that starts from another query's result, so fixes flow through."),
    ("Refresh", "Rerunning every query step, or rebuilding a pivot, on the current source data."),
    ("Show Values As", "Pivot option that displays values as % of total, differences, running totals or ranks."),
    ("Slicer", "Filter buttons for one field, connected to one or more PivotTables."),
    ("Text qualifier", "The character (usually \") that wraps a field containing the delimiter."),
    ("Timeline", "A slider that filters a PivotTable by a date field."),
    ("Unpivot", "Turning a set of columns into Attribute and Value rows: wide to long."),
], key=lambda kv: kv[0].lower())
