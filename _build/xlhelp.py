def pivot(self, tref: "TRef", rows, values, columns=None, filters=None, height=None, style="PivotStyleMedium2",
          layout="tabular", c0=1):
    """Insert a real PivotTable (Excel builds it on open) sourced from a TRef."""
    src = [tref.sheet, tref.r0, tref.c0, tref.r0 + tref.n, tref.c0 + len(tref.cols) - 1]
    opts = {"source": src, "rows": rows, "values": values, "style": style, "layout": layout}
    if columns:
        opts["columns"] = columns
    if filters:
        opts["filters"] = filters
    self.ws.add_pivot_table(self.r, c0, opts)
    self.r += height or 14
    return self


def addr(self, r, c, absolute=False):
    return xl_rowcol_to_cell(r, c, absolute, absolute)


def mtext(self, r, c0, c1, text, fmt):
    """Merged range holding literal text (never interpreted as a formula)."""
    if c1 > c0:
        self.ws.merge_range(r, c0, r, c1, "", fmt)
    self.ws.write_string(r, c0, str(text), fmt)


